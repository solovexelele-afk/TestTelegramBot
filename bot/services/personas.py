# ---------- постобработка ответа: «как живой человек» ----------
_MD_RE = re.compile(r"(\*\*|__|\*|`|^#+\s*)", re.MULTILINE)
_ASSISTANT_TAILS = re.compile(
    r"\s*(если (что|что-то|будут вопросы)[^\n]*(обращайся|пиши|спрашивай)[^\n]*|чем (ещё )?могу помочь\??)\s*$",
    re.IGNORECASE,
)


_SENTENCE_START = re.compile(r"(^|[.!?…]\s+)([A-ZА-ЯЁ])(?=[a-zа-яё]|[\s,!?.]|$)")


def _lower_first(s: str) -> str:
    # начало каждого предложения — с маленькой; аббревиатуры (США, ИИ) не трогаем
    return _SENTENCE_START.sub(lambda m: m.group(1) + m.group(2).lower(), s)


_THOUGHT_RE = re.compile(r"<thought>.*?</thought>|</?thought>|</?think(ing)?>", re.IGNORECASE | re.DOTALL)


def humanize(text: str, max_parts: int = 4, lowercase: bool = True) -> list[str]:
    """Делает ответ похожим на живую переписку и делит на отдельные сообщения.

    lowercase=False — не трогать регистр (автоответчик копирует манеру владельца как есть).
    """
    text = _THOUGHT_RE.sub("", text)
    text = _REACTION_RE.sub("", text)
    text = _MD_RE.sub("", text).strip()
    text = _ASSISTANT_TAILS.sub("", text).strip()
    raw_parts = [p.strip(" -•\t") for p in re.split(r"\n+", text) if p.strip(" -•\t")]
    parts: list[str] = []
    for p in raw_parts:
        if lowercase:
            p = _lower_first(p)
        # одиночная точка в конце — убираем (многоточие оставляем)
        if p.endswith(".") and not p.endswith(".."):
            p = p[:-1]
        parts.append(p)
    if not parts:
        return [text] if text else []
    if len(parts) > max_parts:
        parts = parts[: max_parts - 1] + [" ".join(parts[max_parts - 1 :])]
    return parts
